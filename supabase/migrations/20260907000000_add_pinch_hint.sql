create or replace function public.pinch_hint_is_member(p_room_id uuid, p_actor_id uuid)
returns boolean language sql stable security definer set search_path = '' as $fn$
  select exists (
    select 1 from public.rooms room
    where room.id = p_room_id and (room.host_id = p_actor_id or exists (
      select 1 from pg_catalog.jsonb_array_elements(case when pg_catalog.jsonb_typeof(room.players) = 'array' then room.players else '[]'::jsonb end) player
      where player ->> 'userId' = p_actor_id::text
    ))
  );
$fn$;

create or replace function public.pinch_hint_draw_hand(p_pool jsonb, p_excluded jsonb default '[]'::jsonb, p_count integer default 3)
returns jsonb language sql volatile set search_path = '' as $fn$
  select coalesce((select pg_catalog.jsonb_agg(item)
    from (select item from pg_catalog.jsonb_array_elements(p_pool) item
      where not exists (select 1 from pg_catalog.jsonb_array_elements(p_excluded) old_item where old_item ->> 'id' = item ->> 'id')
      order by pg_catalog.random() limit p_count) drawn), '[]'::jsonb);
$fn$;

create or replace function public.pinch_hint_initialize(p_room_id uuid, p_rounds integer)
returns jsonb language plpgsql security definer set search_path = '' as $fn$
declare
  actor uuid := (select auth.uid()); r public.rooms%rowtype; state jsonb; ids text[]; scores jsonb;
  pool jsonb := public.pinch_hint_item_pool(); topics text[] := public.pinch_hint_topic_pool(); player_entry jsonb; hand jsonb;
begin
  if actor is null or p_rounds is null or p_rounds not between 1 and 3 then raise exception 'ラウンド数は1〜3で指定してください'; end if;
  select * into r from public.rooms where id = p_room_id for update;
  if not found or r.game_type <> 'pinch-hint' or r.status <> 'playing' or r.host_id <> actor then raise exception 'ホストだけがピンチにひらめきを開始できます'; end if;
  if pg_catalog.jsonb_typeof(r.players) <> 'array' or pg_catalog.jsonb_array_length(r.players) not between 2 and 10 then raise exception '2〜10人で遊んでください'; end if;
  if r.game_state is not null and r.game_state <> '{}'::jsonb and r.game_state ->> 'phase' is distinct from 'rule_setting' then raise exception 'このゲームはすでに開始しています'; end if;
  select pg_catalog.array_agg(entry.value ->> 'userId' order by pg_catalog.random()) into ids from pg_catalog.jsonb_array_elements(r.players) as entry(value);
  if (select count(distinct id) from pg_catalog.unnest(ids) id) <> pg_catalog.cardinality(ids)
    or not (actor::text = any(ids)) then raise exception '参加プレイヤーを確認してください'; end if;
  select pg_catalog.jsonb_object_agg(id, 0) into scores from pg_catalog.unnest(ids) id;
  state := pg_catalog.jsonb_build_object('game','pinch-hint','version',1,'matchId',gen_random_uuid()::text,'stateRevision',0,'phase','turn_setup','rounds',p_rounds,'round',1,'turnIndex',0,
    'totalTurns',pg_catalog.array_length(ids,1) * p_rounds,'turnOrder',to_jsonb(ids),'currentPlayerId',ids[1],
    'topic',topics[1 + pg_catalog.floor(pg_catalog.random() * pg_catalog.array_length(topics,1))::integer],
    'requiredCount',1 + pg_catalog.floor(pg_catalog.random() * 3)::integer,'revealedItems','[]'::jsonb,'votedPlayerIds','[]'::jsonb,'scores',scores,'result',null);
  state := state || pg_catalog.jsonb_build_object('usedTopics',pg_catalog.jsonb_build_array(state->>'topic'));
  delete from private.pinch_hint_player_state where room_id = p_room_id;
  for player_entry in select entry.value from pg_catalog.jsonb_array_elements(r.players) as entry(value) loop
    hand := public.pinch_hint_draw_hand(pool);
    insert into private.pinch_hint_player_state(room_id, player_id, hand, selection, vote)
      values(p_room_id, (player_entry ->> 'userId')::uuid, hand, null, null)
      on conflict(room_id, player_id) do update set hand=excluded.hand, selection=null, vote=null;
  end loop;
  update public.rooms set game_state = state where id = p_room_id;
  return state;
end;
$fn$;

create or replace function public.pinch_hint_get_private(p_room_id uuid)
returns jsonb language plpgsql security definer set search_path = '' as $fn$
declare actor uuid := (select auth.uid()); result jsonb; r public.rooms%rowtype;
begin
  select * into r from public.rooms where id=p_room_id for share;
  if actor is null or not public.pinch_hint_is_member(p_room_id, actor)
    or r.game_type is distinct from 'pinch-hint' or r.status is distinct from 'playing'
    then raise exception 'ルームの参加者だけが手札を取得できます'; end if;
  select pg_catalog.jsonb_build_object('hand', ps.hand, 'selection', ps.selection, 'vote', ps.vote) into result
    from private.pinch_hint_player_state ps where room_id=p_room_id and player_id=actor;
  return coalesce(result, pg_catalog.jsonb_build_object('hand','[]'::jsonb,'selection',null,'vote',null))
    || pg_catalog.jsonb_build_object('matchId',r.game_state->>'matchId','turnIndex',r.game_state->'turnIndex','stateRevision',r.game_state->'stateRevision');
end;
$fn$;

create or replace function public.pinch_hint_prepare(p_room_id uuid, p_selection text[], p_expected_turn_index integer, p_expected_match_id text)
returns jsonb language plpgsql security definer set search_path = '' as $fn$
declare actor uuid := (select auth.uid()); r public.rooms%rowtype; state jsonb; hand jsonb; item_id text; distinct_count integer;
begin
  select * into r from public.rooms where id=p_room_id for update; state:=r.game_state;
  if actor is null or p_expected_match_id is null or state->>'matchId' is distinct from p_expected_match_id or state->>'game' is distinct from 'pinch-hint' or not public.pinch_hint_is_member(p_room_id,actor) or r.game_type is distinct from 'pinch-hint' or r.status is distinct from 'playing' or state->>'game' is distinct from 'pinch-hint' or state->>'phase' is distinct from 'turn_setup' or state->>'currentPlayerId' is distinct from actor::text or (state->>'turnIndex')::integer is distinct from p_expected_turn_index then raise exception 'いまはこのプレイヤーの準備時間ではありません'; end if;
  select player_state.hand into hand from private.pinch_hint_player_state player_state where room_id=p_room_id and player_id=actor for update;
  if p_selection is null or pg_catalog.array_ndims(p_selection) is distinct from 1 or pg_catalog.cardinality(p_selection) <> (state->>'requiredCount')::integer then raise exception '指定された枚数のアイテムを選んでください'; end if;
  select count(distinct value) into distinct_count from pg_catalog.unnest(p_selection) value;
  if distinct_count <> pg_catalog.cardinality(p_selection) then raise exception '同じアイテムは一度だけ選べます'; end if;
  foreach item_id in array p_selection loop
    if not exists (select 1 from pg_catalog.jsonb_array_elements(hand) item where item->>'id'=item_id) then raise exception '手札にないアイテムは選べません'; end if;
  end loop;
  update private.pinch_hint_player_state set selection=to_jsonb(p_selection), vote=null where room_id=p_room_id and player_id=actor;
  state:=state || pg_catalog.jsonb_build_object('phase','presenting','revealedItems','[]'::jsonb,'votedPlayerIds','[]'::jsonb,'result',null);
  state:=state || pg_catalog.jsonb_build_object('stateRevision',coalesce((state->>'stateRevision')::integer,0)+1);
  update public.rooms set game_state=state where id=p_room_id; return state;
end;
$fn$;

create or replace function public.pinch_hint_reveal(p_room_id uuid, p_expected_turn_index integer, p_expected_index integer, p_expected_match_id text)
returns jsonb language plpgsql security definer set search_path = '' as $fn$
declare actor uuid := (select auth.uid()); r public.rooms%rowtype; state jsonb; private_state private.pinch_hint_player_state%rowtype; item jsonb; item_id text;
begin
  select * into r from public.rooms where id=p_room_id for update; state:=r.game_state;
  if actor is null or p_expected_match_id is null or state->>'matchId' is distinct from p_expected_match_id or state->>'game' is distinct from 'pinch-hint' or not public.pinch_hint_is_member(p_room_id,actor) or r.game_type is distinct from 'pinch-hint' or r.status is distinct from 'playing' or state->>'phase' is distinct from 'presenting' or state->>'currentPlayerId' is distinct from actor::text or (state->>'turnIndex')::integer is distinct from p_expected_turn_index or p_expected_index is distinct from pg_catalog.jsonb_array_length(state->'revealedItems') then raise exception '次のアイテムを公開できません'; end if;
  if p_expected_index < 0 or p_expected_index >= (state->>'requiredCount')::integer then raise exception '公開できるアイテムがありません'; end if;
  select * into private_state from private.pinch_hint_player_state where room_id=p_room_id and player_id=actor for update;
  item_id := private_state.selection ->> p_expected_index;
  select candidate into item from pg_catalog.jsonb_array_elements(private_state.hand) candidate where candidate->>'id'=item_id;
  if item is null then raise exception '選択したアイテムが見つかりません'; end if;
  item := item || pg_catalog.jsonb_build_object('revealedAt',p_expected_index);
  state:=pg_catalog.jsonb_set(state,'{revealedItems}',state->'revealedItems' || pg_catalog.jsonb_build_array(item));
  state:=state || pg_catalog.jsonb_build_object('stateRevision',coalesce((state->>'stateRevision')::integer,0)+1);
  update public.rooms set game_state=state where id=p_room_id; return state;
end;
$fn$;


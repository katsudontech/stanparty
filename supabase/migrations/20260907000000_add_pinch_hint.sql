create or replace function public.pinch_hint_vote(p_room_id uuid, p_expected_turn_index integer, p_vote text, p_expected_match_id text)
returns jsonb language plpgsql security definer set search_path = '' as $fn$
declare actor uuid := (select auth.uid()); r public.rooms%rowtype; state jsonb; current_id uuid; expected integer; yes_count integer; no_count integer; voted_count integer; success boolean; current_private private.pinch_hint_player_state%rowtype; remaining jsonb; refill jsonb; new_hand jsonb; selection_ids text[]; scores jsonb;
begin
  select * into r from public.rooms where id=p_room_id for update; state:=r.game_state; current_id:=(state->>'currentPlayerId')::uuid;
  if actor is null or p_expected_match_id is null or state->>'matchId' is distinct from p_expected_match_id or state->>'game' is distinct from 'pinch-hint' or p_vote is null or p_vote not in ('yes','no') or not public.pinch_hint_is_member(p_room_id,actor) or r.game_type is distinct from 'pinch-hint' or r.status is distinct from 'playing' or state->>'phase' is distinct from 'voting' or actor = current_id or (state->>'turnIndex')::integer is distinct from p_expected_turn_index then raise exception 'いまは投票できません'; end if;
  select * into current_private from private.pinch_hint_player_state where room_id=p_room_id and player_id=current_id for update;
  if exists(select 1 from private.pinch_hint_player_state where room_id=p_room_id and player_id=actor and vote is not null) then raise exception '投票は一度だけです'; end if;
  if not (state->'turnOrder' ? actor::text) then raise exception 'このゲームの参加者だけが投票できます'; end if;
  update private.pinch_hint_player_state set vote=p_vote where room_id=p_room_id and player_id=actor;
  if not found then raise exception 'プレイヤーの手札が見つかりません'; end if;
  select count(*) filter (where vote='yes'), count(*) filter (where vote='no'), count(*) into yes_count,no_count,voted_count
    from private.pinch_hint_player_state where room_id=p_room_id and player_id in (select (value)::uuid from pg_catalog.jsonb_array_elements_text(state->'turnOrder')) and player_id <> current_id and vote is not null;
  state:=pg_catalog.jsonb_set(state,'{votedPlayerIds}',coalesce(state->'votedPlayerIds','[]'::jsonb) || pg_catalog.jsonb_build_array(actor::text));
  expected:=pg_catalog.jsonb_array_length(state->'turnOrder')-1;
  if voted_count < expected then
    state:=state || pg_catalog.jsonb_build_object('stateRevision',coalesce((state->>'stateRevision')::integer,0)+1);
    update public.rooms set game_state=state where id=p_room_id; return state;
  end if;
  success:=yes_count > no_count;
  scores:=state->'scores';
  if success then scores:=pg_catalog.jsonb_set(scores,ARRAY[current_id::text],to_jsonb(coalesce((scores->>current_id::text)::integer,0)+1),true); end if;
  selection_ids:=array(select value from pg_catalog.jsonb_array_elements_text(current_private.selection) value);
  select coalesce(pg_catalog.jsonb_agg(item), '[]'::jsonb) into remaining from pg_catalog.jsonb_array_elements(current_private.hand) item where not exists(select 1 from pg_catalog.unnest(selection_ids) used where used=item->>'id');
  refill:=public.pinch_hint_draw_hand(public.pinch_hint_item_pool(),current_private.hand,(state->>'requiredCount')::integer);
  new_hand:=remaining || refill;
  update private.pinch_hint_player_state set hand=new_hand,selection=null,vote=null where room_id=p_room_id and player_id=current_id;
  state:=state || pg_catalog.jsonb_build_object('phase','result','scores',scores,'result',pg_catalog.jsonb_build_object('success',success,'yes',yes_count,'no',no_count,'playerId',current_id::text),'stateRevision',coalesce((state->>'stateRevision')::integer,0)+1);
  update public.rooms set game_state=state where id=p_room_id; return state;
end;
$fn$;

create or replace function public.pinch_hint_next_turn(p_room_id uuid, p_expected_turn_index integer, p_expected_match_id text)
returns jsonb language plpgsql security definer set search_path = '' as $fn$
declare actor uuid := (select auth.uid()); r public.rooms%rowtype; state jsonb; ids jsonb; next_index integer; players_per_round integer; topics text[]:=public.pinch_hint_topic_pool();
begin
  select * into r from public.rooms where id=p_room_id for update; state:=r.game_state;
  if actor is null or p_expected_match_id is null or state->>'matchId' is distinct from p_expected_match_id or state->>'game' is distinct from 'pinch-hint' or r.host_id is distinct from actor or r.game_type is distinct from 'pinch-hint' or r.status is distinct from 'playing' or state->>'phase' is distinct from 'result' or (state->>'turnIndex')::integer is distinct from p_expected_turn_index then raise exception 'ホストだけが次のターンへ進めます'; end if;
  ids:=state->'turnOrder'; next_index:=(state->>'turnIndex')::integer+1; players_per_round:=pg_catalog.jsonb_array_length(ids);
  update private.pinch_hint_player_state set vote=null where room_id=p_room_id;
  if next_index >= (state->>'totalTurns')::integer then state:=state || pg_catalog.jsonb_build_object('phase','finished','currentPlayerId',null,'revealedItems','[]'::jsonb); else
    topics := ARRAY(select topic from pg_catalog.unnest(topics) topic
      where not (coalesce(state->'usedTopics','[]'::jsonb) ? topic));
    state:=state || pg_catalog.jsonb_build_object('phase','turn_setup','turnIndex',next_index,'round',1 + (next_index / players_per_round), 'currentPlayerId',ids->>(next_index % players_per_round),
      'topic',topics[1 + pg_catalog.floor(pg_catalog.random() * pg_catalog.array_length(topics,1))::integer], 'requiredCount',1 + pg_catalog.floor(pg_catalog.random()*3)::integer,'revealedItems','[]'::jsonb,'votedPlayerIds','[]'::jsonb,'result',null);
    state := state || pg_catalog.jsonb_build_object('usedTopics',state->'usedTopics' || pg_catalog.jsonb_build_array(state->>'topic'));
  end if;
  state:=state || pg_catalog.jsonb_build_object('stateRevision',coalesce((state->>'stateRevision')::integer,0)+1);
  update public.rooms set game_state=state where id=p_room_id; return state;
end;
$fn$;

create or replace function public.reject_pinch_hint_direct_state_update()
returns trigger language plpgsql set search_path = '' as $fn$
begin
  -- Keep the starting roster even if a generic leave/kick RPC is called while
  -- a phone is disconnected. Returning to the lobby unlocks membership changes.
  if old.game_type = 'pinch-hint' and old.status = 'playing'
    and old.game_state->>'matchId' is not null and new.status <> 'waiting' then
    if new.game_type is distinct from old.game_type or
      (select pg_catalog.jsonb_agg(p->>'userId' order by p->>'userId') from pg_catalog.jsonb_array_elements(new.players) p)
      is distinct from
      (select pg_catalog.jsonb_agg(p->>'userId' order by p->>'userId') from pg_catalog.jsonb_array_elements(old.players) p)
      then raise exception '進行中の参加者は変更できません。先にロビーへ戻ってください'; end if;
  end if;
  if current_user='authenticated' and (old.game_type='pinch-hint' or new.game_type='pinch-hint')
    and new.game_state is distinct from old.game_state
    and not (new.status='waiting' and new.game_state='{}'::jsonb)
    then raise exception 'ピンチにひらめき！の状態はサーバー操作でのみ変更できます'; end if;
  return new;
end;

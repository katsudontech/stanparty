// Edit content.json, then redirect this output to a new Supabase migration.
// Never reapply an already deployed migration just to update the card content.
import { readFile } from 'node:fs/promises';
const { items, topics } = JSON.parse(await readFile(new URL('../src/games/pinch-hint/content.json', import.meta.url), 'utf8'));
const quote = (value) => `'${value.replaceAll("'", "''")}'`;
if (
  !Array.isArray(items) || !Array.isArray(topics) || items.length < 6 || topics.length < 30 ||
  items.some(item => !item || ['id', 'name', 'icon'].some(key => typeof item[key] !== 'string' || !item[key].trim())) ||
  topics.some(topic => typeof topic !== 'string' || !topic.trim()) ||
  new Set(items.map(item => item.id)).size !== items.length || new Set(topics).size !== topics.length
) {
  throw new Error('Content needs at least 6 unique items and 30 unique topics for a full ten-player, three-round game.');
}
process.stdout.write(`-- Generated by scripts/generate-pinch-content.mjs from content.json.
create or replace function public.pinch_hint_item_pool()
returns jsonb language sql immutable set search_path = '' as $fn$
  select ${quote(JSON.stringify(items))}::jsonb;
$fn$;

create or replace function public.pinch_hint_topic_pool()
returns text[] language sql immutable set search_path = '' as $fn$
  select ARRAY[\n${topics.map(topic => `    ${quote(topic)}`).join(',\n')}\n  ];
$fn$;

revoke all on function public.pinch_hint_item_pool() from public, anon, authenticated;
revoke all on function public.pinch_hint_topic_pool() from public, anon, authenticated;
`);
